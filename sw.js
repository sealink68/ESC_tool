var CACHE_PREFIX = "esc-shell-";
var CACHE_VERSION = CACHE_PREFIX + "v2-" + PRECACHE_HASH;
var NET_TIMEOUT = 3000;
var CORE = /(^\.\/$|\.(html|css|js|json|webmanifest)$)/i;

function abs(u) { return new URL(u, self.registration.scope).href; }
/* fetch one file bypassing the HTTP cache; a redirected response is re-wrapped (navigations refuse redirected responses) */
function grab(u) {
  return fetch(new Request(abs(u), { cache: "reload", credentials: "same-origin" })).then(function (r) {
    if (!r.ok) throw new Error("HTTP " + r.status);
    return r.redirected ? r.blob().then(function (b) { return new Response(b, { status: 200, headers: r.headers }); }) : r;
  });
}
function cacheOne(c, u, tries) {
  return grab(u).then(function (r) { return c.put(abs(u), r); }).then(function () { return null; }, function (e) {
    if (tries > 1) return cacheOne(c, u, tries - 1);
    return { url: u, error: String((e && e.message) || e) };
  });
}
/* a few parallel downloads; resolves with the list of failures */
function cacheAll(c, list) {
  var i = 0, failed = [];
  function next() {
    if (i >= list.length) return Promise.resolve();
    var u = list[i++];
    return cacheOne(c, u, 2).then(function (f) { if (f) failed.push(f); return next(); });
  }
  var lanes = []; for (var k = 0; k < 6; k++) lanes.push(next());
  return Promise.all(lanes).then(function () { return failed; });
}
function missing(c) {
  return Promise.all(PRECACHE.map(function (u) { return c.match(abs(u)).then(function (r) { return r ? null : u; }); }))
    .then(function (l) { return l.filter(Boolean); });
}
function tell(msg) {
  return self.clients.matchAll({ includeUncontrolled: true, type: "window" }).then(function (cl) { cl.forEach(function (c) { c.postMessage(msg); }); });
}
function report(c) {
  return missing(c).then(function (m) {
    var st = { type: "PRECACHE_STATUS", version: CACHE_VERSION, total: PRECACHE.length, cached: PRECACHE.length - m.length, missing: m, bytes: PRECACHE_BYTES, complete: !m.length };
    return st;
  });
}
/* fetch whatever is still missing (images that failed during install); calls are queued, each one checks afresh */
var topQueue = Promise.resolve();
function topUp() {
  var run = function () {
    return caches.open(CACHE_VERSION).then(function (c) {
      return missing(c).then(function (m) { return m.length ? cacheAll(c, m) : []; }).then(function () { return report(c); });
    }).then(function (st) { if (st.complete) tell(st); return st; });
  };
  var p = topQueue.then(run, run);
  topQueue = p.catch(function () {});
  return p;
}

self.addEventListener("install", function (e) {
  e.waitUntil(caches.open(CACHE_VERSION).then(function (c) {
    return cacheAll(c, PRECACHE).then(function (failed) {
      var core = failed.filter(function (f) { return CORE.test(f.url); });
      if (failed.length) console.warn("[ESC_tool sw] precache: " + failed.length + " file(s) failed:", JSON.stringify(failed));
      if (core.length) { // without these the app would not start offline: keep the previous version
        console.error("[ESC_tool sw] install aborted, core file(s) missing:", JSON.stringify(core));
        return caches.delete(CACHE_VERSION).then(function () { throw new Error("core precache failed: " + core.map(function (f) { return f.url; }).join(", ")); });
      }
      return report(c).then(tell);
    });
  }));
});

self.addEventListener("activate", function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf(CACHE_PREFIX) === 0 && k !== CACHE_VERSION; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }).then(function () { topUp().catch(function () {}); }));
});

self.addEventListener("message", function (e) {
  var d = e.data || {}, port = e.ports && e.ports[0];
  if (d.type === "SKIP_WAITING") { self.skipWaiting(); return; }
  if (d.type === "STATUS" || d.type === "TOPUP") {
    var p = d.type === "TOPUP" ? topUp() : caches.open(CACHE_VERSION).then(report);
    e.waitUntil(p.then(function (st) { if (port) port.postMessage(st); }, function (x) { if (port) port.postMessage({ type: "PRECACHE_STATUS", error: String(x) }); }));
  }
});

function put(key, res) {
  if (res && res.ok && res.type === "basic" && !res.redirected) {
    var copy = res.clone(); caches.open(CACHE_VERSION).then(function (c) { return c.put(key, copy); }).catch(function () {});
  }
  return res;
}
function fromCache(key, nav) {
  return caches.match(key, { ignoreSearch: nav }).then(function (hit) {
    if (hit || !nav) return hit;
    return caches.match(abs("./")).then(function (h) { return h || caches.match(abs("index.html")); });
  });
}
/* network-first: the network answer wins if it comes within NET_TIMEOUT; after that the cached copy is used
   (the network answer still refreshes the cache in the background). Network error / 5xx -> cache. */
function networkFirst(e, req, key, nav) {
  return new Promise(function (resolve) {
    var done = false, timer = 0;
    function finish(r) { if (!done && r) { done = true; clearTimeout(timer); resolve(r); } }
    var net = fetch(new Request(req.url, { cache: "no-cache", credentials: "same-origin" })).then(function (r) { return put(key, r); });
    e.waitUntil(net.catch(function () {}));
    timer = setTimeout(function () { fromCache(key, nav).then(finish); }, NET_TIMEOUT);
    net.then(function (r) {
      if (r.status >= 500) return fromCache(key, nav).then(function (h) { finish(h || r); });
      finish(r);
    }, function () {
      fromCache(key, nav).then(function (h) { finish(h || Response.error()); });
    });
  });
}

self.addEventListener("fetch", function (e) {
  var req = e.request, url;
  if (req.method !== "GET" || req.headers.has("range")) return;
  try { url = new URL(req.url); } catch (x) { return; }
  if (url.origin !== self.location.origin || url.href.indexOf(self.registration.scope) !== 0) return;
  var nav = req.mode === "navigate", img = /\.(png|jpe?g|svg|ico|webp|gif)$/i.test(url.pathname);
  if (img) { // cache-first (all images are precached)
    e.respondWith(caches.match(req).then(function (hit) { return hit || fetch(req).then(function (r) { return put(req, r); }); }));
    return;
  }
  e.respondWith(networkFirst(e, req, nav ? url.origin + url.pathname : req, nav));
});
